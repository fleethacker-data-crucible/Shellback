// Generates src/app/components/icons.tsx from Lucide's SVG sources, so the UI ships only the icons it
// uses and never loads anything from a CDN (docs/UNIFIED-UI.md section 6).
//   npm pack lucide-static@1.54.0 && tar -xzf lucide-static-1.54.0.tgz
//   node tools/gen-icons.mjs package/icons
// The output is committed; re-run only when the icon list changes.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const LUCIDE_VERSION = '1.54.0';
// Shellback's icon name -> Lucide icon name.
const ICONS = {
  home: 'house',
  profile: 'user-round',
  explore: 'orbit',
  team: 'users',
  program: 'layers',
  export: 'download',
  import: 'upload',
  power: 'power',
  themeSystem: 'sun-moon',
  themeLight: 'sun',
  themeDark: 'moon',
  menu: 'menu',
};

const dir = process.argv[2];
if (!dir) throw new Error('Usage: node tools/gen-icons.mjs <lucide-static>/icons');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const shapes = {};
for (const [name, lucide] of Object.entries(ICONS)) {
  const svg = readFileSync(path.join(dir, `${lucide}.svg`), 'utf8');
  const body = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>'));
  shapes[name] = [...body.matchAll(/<(\w+)([^>]*?)\/>/g)].map(([, tag, attrs]) => [tag, Object.fromEntries([...attrs.matchAll(/([\w-]+)="([^"]*)"/g)].map(([, k, v]) => [k, v]))]);
}

const out = `// GENERATED by tools/gen-icons.mjs from Lucide ${LUCIDE_VERSION} (ISC licence, https://lucide.dev). Do not edit.
// 16 px in controls, 20 px in navigation, 1.75 px stroke, currentColor (docs/UNIFIED-UI.md section 6).
import { createElement } from 'react';

const ICONS = {
${Object.entries(shapes).map(([name, parts]) => `  ${name}: ${JSON.stringify(parts)}, // ${ICONS[name]}`).join('\n')}
} as const satisfies Record<string, ReadonlyArray<readonly [string, Record<string, string>]>>;

export type IconName = keyof typeof ICONS;

export function Icon({ name, size = 16, className }: { name: IconName; size?: number; className?: string }) {
  return (
    <svg width={size} height={size} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth={1.75} strokeLinecap="round" strokeLinejoin="round" className={className} aria-hidden="true" focusable="false">
      {ICONS[name].map(([tag, attrs], i) => createElement(tag, { key: i, ...attrs }))}
    </svg>
  );
}
`;
writeFileSync(path.join(root, 'src/app/components/icons.tsx'), out);
console.log(`src/app/components/icons.tsx: ${Object.keys(ICONS).length} icons from Lucide ${LUCIDE_VERSION}`);
